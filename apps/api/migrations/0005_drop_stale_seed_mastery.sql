-- 删掉 `seed.sql` 曾经插入的那行「没有证据支撑的掌握度快照」。
--
-- ## 为什么要迁移，而不是只把 seed.sql 里那行删掉
--
-- `seed.sql` 只影响**新建**的库。已经跑过 `pnpm db:seed` 的库（包括开发库和每个
-- 队友的库）里那一行还在，而且它会继续被读出来 —— `GET /api/v1/graph` 读
-- `app.mastery` 的快照，`GET /api/v1/mastery/:id` 读 `app.attempts` 回放，两条
-- 路径对同一个知识点给出两套掌握度：
--
--   图谱/详情页：kp-bool 已熟悉 66%（来自快照）
--   掌握度接口：kp-bool unseen、0 次作答（来自回放）
--
-- 用户打开详情页，标题旁边写 66%，下面的掌握度条说「未学习」。修复必须同时覆盖
-- 新建库和已有库，所以既要删 seed 里那行，也要用迁移清掉存量。
--
-- ## 为什么不是「补一批 attempts 让它自洽」
--
-- 那需要反推「哪 10 道题、什么对错序列，BKT 回放出来正好 0.7200 / 0.6600」。
-- 那是为了让一个假数字继续存在而伪造证据 —— 方向反了。`app.attempts` 是学习者
-- 行为的记录，是掌握度的**唯一**合法来源；没有作答就是没有掌握，那才是真的。
--
-- ## 为什么条件是「没有对应 attempts」而不是按数值指纹匹配
--
-- 按 `achieved=0.72 AND current=0.66 AND attempt_count=10` 匹配也能命中这一行，
-- 但那个条件描述的是「长得像种子的行」，而不是「错在哪」。真正错的地方是
-- **掌握度没有证据支撑**：`attempt_count` 声称 10 次作答，而 `app.attempts`
-- 一张相关记录都没有。用 `NOT EXISTS` 表达这一点，条件本身就说明了缺陷是什么；
-- 而且万一这个知识点将来真的有学习者作答过，这一行就带着真证据，不该删。
--
-- 作用域限定在 `kp-bool`：迁移只应删掉它被写来删的东西。别的知识点上若有
-- 类似的孤立快照，那是另一件事，应当单独判断，而不是被这条顺手抹掉。
DELETE FROM app.mastery m
WHERE m.micro_kp_id = 'kp-bool'
  AND NOT EXISTS (
    SELECT 1 FROM app.attempts a WHERE a.micro_kp_id = m.micro_kp_id
  );
