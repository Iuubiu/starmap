-- 回滚 0004：恢复 spec 列的默认值。
--
-- ## 为什么不把 lv-bool-1 插回来
--
-- 「回滚」的语义是把 schema 退回上一个状态，不是把已确认的坏数据重新种一遍。
-- 那条关卡的 spec 是 `{}`（见 up 文件里的说明：DEFAULT 把它从插入时错误变成了
-- 运行时 500），回滚迁移重新引入它，等于让每一个执行过回滚的库再次带着一个
-- 点开就炸的关卡 —— 而回滚恰恰通常发生在「线上出事了」的时候。
--
-- 数据一旦被判定为缺陷就只向前删，不向后恢复。想重新要一条布尔代数的教学
-- 关卡，0010 的 lv-bool-laws 就是它，且带完整 spec。
--
-- ## 为什么恢复 DEFAULT 反而是对的
--
-- DEFAULT 本身是 0001 的既定 schema 形状，回滚 0004 就该回到那个形状。它是个
-- 陷阱，但陷阱属于 0001；要永久撤掉它需要改 0001（会破坏已有库的迁移校验和）。
-- 所以：0004 上行撤掉它（当前状态更安全），0004 下行恢复它（回到 0001 的形状）。
-- 将来若要彻底消除，应当新开一条迁移而不是改历史文件。

ALTER TABLE app.levels ALTER COLUMN spec SET DEFAULT '{}'::jsonb;
