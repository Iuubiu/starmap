#: 连接词：在句式重排里当分隔符用，不当普通词。
CONNECTORS = {
    'of': '的',
    'for': '用于',
    'in': '中',
    'between': '之间',
    'based on': '基于',
    'with': '带',
}

_WORD = re.compile(r"[A-Za-z]+(?:'[A-Za-z]+)?|[0-9]+(?:\.[0-9]+)*|[^\sA-Za-z0-9]")
# 编号前缀有四种真实形态：`1.2.3` / `IV.` / `B.4`（字母段） / `10.1.A`（字母段在尾）。
# 最后两种是 ahmed-2e 附录小节的写法（`B.4 Wilkinson ADC`、`10.1.A ROOT`），
# 漏了会把编号当成正文一起送进逐词匹配，整条标题因此译不出来。
_LEAD_NUMBER = re.compile(
    r'^\s*(?:'
    r'\d+(?:\.\d+)*\.?'          # 1.2.3 / 1.2.3.
    r'|\d+(?:\.\d+)*\.[A-Z]\.?'  # 10.1.A / 10.1.C
    r'|[A-Z]\.\d+(?:\.\d+)*\.?'  # B.4
    r'|[IVXLC]+\.'                 # IV.
    r')\s+'
)
_TRAIL_PUNCT = re.compile(r'[\s.·\-—–:;,]+$')
_LEAD_PUNCT = re.compile(r'^[\s.·\-—–:;,|]+')
_LIGATURES = {'ﬁ': 'fi', 'ﬀ': 'ff', 'ﬂ': 'fl', 'ﬃ': 'ffi', 'ﬄ': 'ffl', 'ﬅ': 'ft', 'ﬆ': 'st'}
# 英文标题的定冠词/不定冠词。`The ADC` 这类整条只有缩写、冠词又不在 DROP_TOKENS 里，
# 不剥掉就永远凑不出汉字。只在 `translate_title` 的开头剥一次，不动逐词表。
_LEAD_ARTICLE = re.compile(r'^(?:The|A|An)\s+')

#: 未收录词计数。`check_names.py` 用它报「还缺哪些词」。
_MISSING: collections.Counter[str] = collections.Counter()

#: 兜底形态的前缀。冒号分支要用它判断「这一半到底译出来没有」——
#: 只看非空不够，兜底串本身也是非空字符串。
_FALLBACK = '未收录术语（'


def untranslated_terms() -> collections.Counter[str]:
    return _MISSING.copy()


def _normalize(title: str) -> str:
    text = title or ''
    for ligature, plain in _LIGATURES.items():
        text = text.replace(ligature, plain)
    return re.sub(r'\s+', ' ', text).strip()


def _strip_number(title: str) -> str:
    m = _LEAD_NUMBER.match(title)
    return title[m.end() :] if m else title


def _stem(word: str) -> str:
    """极轻量的复数/词尾归一化。**只用于查表**，不改输出。"""
    lowered = word.lower()
    for suffix, replacement in (('ies', 'y'), ('es', ''), ('s', '')):
        if lowered.endswith(suffix) and len(lowered) - len(suffix) >= 4:
            return lowered[: -len(suffix)] + replacement
    return lowered


def _lookup(words: list[str], start: int, table: dict[str, str]) -> tuple[int, str] | None:
    """在 `start` 位置做**最长**匹配，返回 (词数, 中文)。"""
    for size in range(min(7, len(words) - start), 0, -1):
        phrase = ' '.join(words[start : start + size]).lower()
        if phrase in table:
            return size, table[phrase]
        stemmed = ' '.join(_stem(w) for w in words[start : start + size])
        if stemmed != phrase and stemmed in table:
            return size, table[stemmed]
    return None


def _translate_words(text: str) -> str:
    words = _WORD.findall(text)
    pieces: list[tuple[str, bool]] = []  # (中文, 是否是连接词)
    index = 0
    while index < len(words):
        hit = _lookup(words, index, GLOSSARY)
        if hit is not None:
            size, chinese = hit
            phrase = ' '.join(words[index : index + size]).lower()
            is_connector = phrase in CONNECTORS or _stem(phrase) in CONNECTORS
            if chinese:
                pieces.append((chinese, is_connector))
            index += size
            continue
        word = words[index]
        lowered = word.lower()
        if lowered in DROP_TOKENS or word.isdigit() or not word[0].isalpha():
            index += 1
            continue
        if lowered in KEEP_TOKENS or _stem(lowered) in KEEP_TOKENS:
            pieces.append((word.upper() if len(word) <= 5 else word, False))
            index += 1
            continue
        _MISSING[_stem(lowered)] += 1
        index += 1

    # 句首句尾的连接词（「的」「与」「中」）是英文语序留下的残渣，去掉；
    # **不能按字符 strip**：那会把「中子源」的中字当连接词删掉（实测得到「子源」）。
    while pieces and pieces[0][1]:
        pieces.pop(0)
    while pieces and pieces[-1][1]:
        pieces.pop()
    joined = ''.join(chinese for chinese, _ in pieces)
    return re.sub(r'的的', '的', joined)


def _split_top(text: str) -> tuple[str, str, str] | None:
    """按第一个顶层连接词切成 (左, 连接词, 右)。用于 `A of B` → `B的A` 这类重排。"""
    lowered = text.lower()
    best: tuple[int, str] | None = None
    for connector in (' of ', ' for ', ' in ', ' between ', ' based on ', ' with '):
        position = lowered.find(connector)
        if position == -1:
            continue
        if best is None or position < best[0]:
            best = (position, connector)
    if best is None:
        return None
    position, connector = best
    return text[:position], connector.strip(), text[position + len(connector) :]


def translate_title(title: str) -> str:
    """把一条英文标题译成中文。**保证返回值含汉字**。

    顺序：剥编号 → 中文原题直接返回 → 冒号分成主/副标题 → 顶层 `X of Y` 重排 →
    逐词最长匹配 → 清掉句首句尾的连接词残渣。

    `A of B` 直译成「A 的 B」是英文语序；中文说「B 的 A」。所以先按连接词切开
    再换位，比逐词拼更接近教材里的写法（`Interaction of Heavy Charged Particles`
    → 「重带电粒子的相互作用」）。
    """
    text = _TRAIL_PUNCT.sub('', _LEAD_PUNCT.sub('', _normalize(title)))
    if not text:
        return ''
    text = _TRAIL_PUNCT.sub('', _LEAD_PUNCT.sub('', _strip_number(text)))
    if not text:
        return ''
    # 冠词在编号之后剥（`A.4 The Laplace transform` → `Laplace transform`）。
    text = _TRAIL_PUNCT.sub('', _LEAD_ARTICLE.sub('', text))
    if not text:
        return ''

    # 中文原题（26/27 郭江）原样返回：已经是中文，再切词只会破坏。
    if re.search(r'[\u4e00-\u9fff]', text):
        return text

    # 冒号：主标题：副标题。两边各自译，用中文冒号连。
    # 左侧没有字母时冒号不是主副标题分隔符，而是「章:节」编号
    # （`6:2 Preservation of timing information`）。按冒号切开只会得到
    # 「未收录术语（6）：定时信息的保持」—— 编号当标题，比不译更糟。
    if ':' in text and re.search(r'[A-Za-z]', text.partition(':')[0]):
        head, _, tail = text.partition(':')
        left, right = translate_title(head), translate_title(tail)
        # 一侧译不出时不能把兜底串拼进结果：`Example of a general-purpose
        # detector: Belle` 会变成「一般探测器的示例：未收录术语（Belle）」，
        # 学生看到的就是这句。宁可只留能译的那半边（`附录 4: Monte Carlo
        # event generators` → 「附录：蒙特卡洛事件产生器」）。
        left_ok = bool(left) and _FALLBACK not in left
        right_ok = bool(right) and _FALLBACK not in right
        if left_ok and right_ok:
            return f'{left}：{right}'[:80]
        # 一侧译不出时不能把兜底串拼进结果：`Example of a general-purpose
        # detector: Belle` 会变成「一般探测器的示例：未收录术语（Belle）」，
        # 学生看到的就是这句。先试整串逐词（`Computer Controlled Electronics:
        # CAMAC` → 「电子学CAMAC」，比只留「电子学」信息量大），再退回能译的
        # 那半边（`Appendix 4: Monte Carlo event generators` → 「附录：蒙特卡洛
        # 事件产生器」）。两边都译不出才落到函数末尾的兜底。
        joined_all = _translate_words(text)
        if re.search(r'[\u4e00-\u9fff]', joined_all):
            return joined_all[:80]
        if left_ok:
            return left[:80]
        if right_ok:
            return right[:80]
        text = head + ' ' + tail

    # 顶层 `X of Y` / `X for Y` 换位。
    split = _split_top(text)
    if split is not None:
        left, connector, right = split
        left_cn = _translate_words(left)
        right_cn = _translate_words(right)
        if left_cn and right_cn:
            if connector == 'of':
                return f'{right_cn}的{left_cn}'[:80]
            if connector == 'for':
                return f'用于{right_cn}的{left_cn}'[:80]
            if connector == 'in':
                return f'{right_cn}中的{left_cn}'[:80]
            if connector == 'between':
                return f'{right_cn}之间的{left_cn}'[:80]
            if connector == 'based on':
                return f'基于{right_cn}的{left_cn}'[:80]
            if connector == 'with':
                return f'{left_cn}（带{right_cn}）'[:80]

    joined = _translate_words(text)
    if not re.search(r'[\u4e00-\u9fff]', joined):
        return f'未收录术语（{text[:40]}）'
    return joined[:80]


def load_overrides(path: str | None = None) -> dict[str, str]:
    """读 `names.zh.json`（LLM 或人工产出的「原文 → 中文」词典）。文件不存在就返回空表。"""
    target = path or os.path.join(os.path.dirname(__file__), 'names.zh.json')
    if not os.path.exists(target):
        return {}
    with open(target, encoding='utf-8') as handle:
        data = json.load(handle)
    return {str(key): str(value) for key, value in data.items()}


def make_translator(overrides: dict[str, str] | None = None):
    """返回 `title -> 中文名`。词典优先于规则。"""
    table = overrides or {}

    def translate(title: str) -> str:
        key = _normalize(title)
        if key in table:
            return table[key]
        return translate_title(key)

    return translate
