def make_paper_translator():
    """返回 `title -> 中文名`，带论文专用术语表。

    ## 为什么要 monkey-patch `translate.GLOSSARY`

    `translate.make_translator(overrides)` 的 `overrides` 是「**整串**原文 →
    中文」的词典，只对完全匹配的标题生效，**不参与逐词翻译** —— 逐词那一步读的
    是模块级的 `GLOSSARY`。所以 `SECTION_GLOSSARY`（`beam` / `event` /
    `tracking` 这些词）必须并进 `GLOSSARY` 才能被 `_translate_words` 用到。

    这是本仓库里唯一一处刻意的跨模块字典注入，理由是：`tools/ingest/translate.py`
    是 content-dev 泳道正在改的文件，直接往里加 200 条论文术语会和他们的改动
    冲突；而复制一份翻译引擎（`_lookup` / `_split_top` / `translate_title` 共
    200 行）会让两份实现迟早漂移。

    ## 顺序

    1. `PAPER_TITLES` 整串命中 → 直接返回（101 篇论文标题都有）
    2. 走 `translate.translate_title`（此时已含 `SECTION_GLOSSARY`）
    """
    import translate  # type: ignore[import-not-found]  # tools/ingest 在 sys.path 上

    # 幂等：重复调用不会把表越叠越大（dict.update 同键覆盖）。
    from paper_glossary_common import SECTION_GLOSSARY_COMMON
    from paper_glossary_extra import SECTION_GLOSSARY_EXTRA
    from paper_glossary_generic import SECTION_GLOSSARY_GENERIC

    translate.GLOSSARY.update(SECTION_GLOSSARY)
    translate.GLOSSARY.update(SECTION_GLOSSARY_EXTRA)
    translate.GLOSSARY.update(SECTION_GLOSSARY_COMMON)
    # 第四轮（通用英语词）最后 update。它与上面三张表已做过差集，没有重叠键，
    # 顺序不影响结果 —— 写在这里只是为了让「后来者最后生效」这条直觉仍然成立。
    translate.GLOSSARY.update(SECTION_GLOSSARY_GENERIC)

    # 整串词典 = 完整标题 + 截断标题。
    table = {**PAPER_TITLES, **TRUNCATED_TITLES}

    def _key(text: str) -> str:
        """归一化到可比较的键。

        必须做，不能直接用 `translate._normalize` —— 那个只合并空白和拆连字
        （ligature），而 `complete_title()` 从 PDF 首页抽出来的标题与人工写的
        键之间还差两件事：

        1. **连字符形**：PDF 里是 U+2014/U+2013（`Mantid—Data analysis`），
           人工键写的是 ASCII `-`。
        2. **标点与大小写**：`NINO: an ultra-fast...` vs `NINO：...`；
           `DEVELOPMENT OF RESISTIVE PLATE COUNTERS` 全大写。

        实测：101 篇里只有 49 条能精确命中，归一化后 93 条，剩 8 条是
        `complete_title()` 没能补全的截断标题（走前缀匹配）。
        """
        text = translate._normalize(text or "").lower()
        text = text.replace("—", "-").replace("–", "-")
        text = re.sub(r"[^a-z0-9]+", " ", text)
        return text.strip()

    by_key = {_key(english): chinese for english, chinese in table.items()}

    def translate_name(title: str) -> str:
        key = _key(title)
        direct = by_key.get(key)
        if direct is not None:
            return direct
        # 前缀匹配：`complete_title()` 补不全的截断标题。
        # 两种形态都要盖：
        #   ① 人工键长 >= 30：拿前 30 字符比（截断位置可能变）
        #   ② 人工键本身就很短：拿整串比前缀（`<mml:math xmlns:mml=` → `mml math
        #      xmlns mml`，归一化后只有 15 字符，不走 ① 就漏了）
        for prefix, value in by_key.items():
            if len(prefix) >= 30:
                if key.startswith(prefix[:30]):
                    return value
            elif key.startswith(prefix):
                return value
        # 最后才退回规则翻译。规则译名会有语序瑕疵（`A of B` 倒装、术语缺漏），
        # 所以上面两层命中优先。
        return translate.translate_title(translate._normalize(title))

    return translate_name
