import { createRequire } from 'node:module';
import { join } from 'node:path';
const requireApi = createRequire(join(process.cwd(), 'apps', 'api', 'package.json'));
const { Client } = requireApi('pg');
const c = new Client({ connectionString: process.env.DATABASE_URL ?? 'postgres://postgres:postgres@127.0.0.1:5432/starmap', options: '-c search_path=app,public' });
await c.connect();
console.log('=== 名字含「作用与地位」 ===');
let r = await c.query(`SELECT id, source_id, parent_id, name, depth, is_leaf, ordinal, source_page FROM knowledge_points WHERE name LIKE '%作用与地位%' ORDER BY source_id, ordinal`);
for (const x of r.rows) console.log(JSON.stringify(x));
console.log('\n=== 名字含「第一节」 ===');
r = await c.query(`SELECT id, source_id, parent_id, name, depth, is_leaf, ordinal, source_page FROM knowledge_points WHERE name LIKE '%第一节%' OR name = '第一节' ORDER BY source_id, ordinal`);
for (const x of r.rows) console.log(JSON.stringify(x));
console.log('\n=== 名字以标点结尾 ===');
r = await c.query(`SELECT id, source_id, parent_id, name, depth, is_leaf, ordinal, source_page FROM knowledge_points WHERE name ~ '[、，。；：（(]$' ORDER BY source_id, ordinal`);
console.log('count=', r.rowCount);
for (const x of r.rows) console.log(JSON.stringify(x));
console.log('\n=== 短名字 (len<=4) 且 is_leaf ===');
r = await c.query(`SELECT id, source_id, parent_id, name, length(name) len, source_page FROM knowledge_points WHERE is_leaf AND length(name) <= 4 ORDER BY len, name`);
console.log('count=', r.rowCount);
for (const x of r.rows.slice(0,60)) console.log(JSON.stringify(x));
await c.end();
