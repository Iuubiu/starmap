import { chromium } from '@playwright/test';
const b = await chromium.launch();
const p = await b.newPage();
await p.goto('http://localhost:5173/');
await p.waitForTimeout(1500);
const kpBadge = await p.locator('text=当前知识点').locator('..').innerText();
console.log('BEFORE:', kpBadge.replace(/\n/g,' | '));
await p.getByLabel('这一轮想说的话').fill('给我一张关卡，我想做题。');
const resp = p.waitForResponse(r => r.url().includes('/agent/turns') && r.request().method()==='POST', {timeout: 120000});
await p.getByRole('button', {name:'提交这一轮'}).click();
const body = await (await resp).json();
console.log('turn1 artifact:', body.artifact?.kind, body.artifact?.microKpId, body.artifact?.title);
await p.waitForTimeout(2000);
const after = await p.locator('text=当前知识点').locator('..').innerText();
console.log('AFTER:', after.replace(/\n/g,' | '));
await p.getByLabel('这一轮想说的话').fill('给我一张关卡，我想做题。');
const resp2 = p.waitForResponse(r => r.url().includes('/agent/turns') && r.request().method()==='POST', {timeout: 120000});
await p.getByRole('button', {name:'提交这一轮'}).click();
const b2 = await (await resp2).json();
console.log('turn2 artifact:', b2.artifact?.kind, b2.artifact?.microKpId, b2.artifact?.title, 'level:', b2.artifact?.levelId);
await b.close();
