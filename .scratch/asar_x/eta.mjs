import fs from 'node:fs';
const t = JSON.parse(fs.readFileSync('D:/DeepSeek/starmap/.agent-teams/starmap-build/team.json', 'utf8'));
const now = Date.now();
const done = t.tasks.filter((x) => x.status === 'completed' && x.updatedAt);
const rows = done.map((x) => ({ id: x.id, kind: x.kind || 'work', who: x.assignee, done: x.updatedAt, dur: x.updatedAt - x.createdAt })).sort((a, b) => a.done - b.done);
const fmt = (ms) => (ms / 60000).toFixed(0) + 'm';
console.log('now=' + new Date(now).toISOString() + ' tasks=' + t.tasks.length + ' completed=' + done.length);
console.log('--- last 10 completions');
for (const r of rows.slice(-10)) console.log(r.id + ' ' + r.kind + ' ' + r.who + ' done@' + new Date(r.done).toISOString().slice(11, 16) + ' dur=' + fmt(r.dur));
const last6 = rows.filter((r) => r.done > now - 6 * 3600e3);
const last3 = rows.filter((r) => r.done > now - 3 * 3600e3);
const last1 = rows.filter((r) => r.done > now - 3600e3);
console.log('throughput: 6h=' + last6.length + ' 3h=' + last3.length + ' 1h=' + last1.length);
const impl = rows.filter((r) => r.kind === 'implementation' || r.kind === 'repair');
const work = rows.filter((r) => r.kind === 'work');
const avg = (a) => (a.reduce((s, r) => s + r.dur, 0) / Math.max(1, a.length) / 60000).toFixed(0);
console.log('avg dur: all=' + avg(rows) + 'm impl=' + avg(impl) + 'm work=' + avg(work) + 'm');
console.log('recent impl durs=' + JSON.stringify(impl.slice(-8).map((r) => fmt(r.dur))));
const open = t.tasks.filter((x) => !['completed', 'cancelled'].includes(x.status));
console.log('--- open');
for (const x of open) console.log(x.id + ' ' + x.status + ' ' + (x.kind || 'work') + ' ' + x.assignee + ' started@' + new Date(x.updatedAt).toISOString().slice(11, 16) + ' age=' + fmt(now - x.updatedAt));
